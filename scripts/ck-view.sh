        i=$((i+1))
        printf '%d. %s/ — %s\n' "$i" "$p" "$(plan_name "$p")"
      done <<<"$PLANS"
      echo
      echo "Showing: ALL plans"
      echo
    fi
    first=1
    while IFS= read -r p; do
      [ -n "$p" ] || continue
      [ "$first" -eq 1 ] || echo
      first=0
      if [ "$MODE" = "status" ]; then render_status "$p"; else render_progress "$p"; fi
    done <<<"$PLANS"
    ;;
esac
